import type {
	IExecuteFunctions,
	INodeExecutionData,
	INodeProperties,
	IDisplayOptions,
	IDataObject,
} from 'n8n-workflow';
import { ApiClient } from '../../../../shared/transport/ApiClient';

export function description(displayOptions: IDisplayOptions): INodeProperties[] {
	return [
		{
			displayName: 'Xdsl Service Name',
			name: 'serviceName',
			type: 'resourceLocator',
			default: { mode: 'list', value: '' },
			required: true,
			description: 'The name of the xDSL service (e.g. xdsl-12345)',
			modes: [
				{
					displayName: 'From List',
					name: 'list',
					type: 'list',
					typeOptions: { searchListMethod: 'getXdslServices', searchable: true },
				},
				{
					displayName: 'By Name',
					name: 'name',
					type: 'string',
					placeholder: 'xdsl-12345',
				},
			],
			displayOptions,
		},
		{
			displayName: 'Subscription ID',
			name: 'subscriptionId',
			type: 'string',
			default: '',
			required: true,
			description: 'Unique identifier of the log subscription',
			displayOptions,
		},
	];
}

/**
 * Get the details of a specific log subscription of an xDSL service.
 *
 * HTTP method: GET
 * Endpoint: /xdsl/{serviceName}/log/subscription/{subscriptionId}
 */
export async function execute(this: IExecuteFunctions, _itemIndex?: number): Promise<INodeExecutionData[]> {
	const client = new ApiClient(this);
	const serviceName = this.getNodeParameter('serviceName', _itemIndex ?? 0, '', { extractValue: true }) as string;
	const subscriptionId = this.getNodeParameter('subscriptionId', _itemIndex ?? 0) as string;

	const data = (await client.httpGet(`/xdsl/${encodeURIComponent(serviceName)}/log/subscription/${encodeURIComponent(subscriptionId)}`)) as IDataObject;
	return this.helpers.returnJsonArray([data]);
}
