import type {
	IDataObject,
	IExecuteFunctions,
	INodeExecutionData,
	INodeProperties,
} from 'n8n-workflow';
import { getClient } from '../../shared/transport/ApiClient';

export function description(): INodeProperties[] {
	return [
		{
			displayName: 'Servicename',
			name: 'serviceName',
			type: 'string',
			default: '',
			required: true,
			description: 'The internal name of your Housing bay',
		},
	];
}

/**
 * Change your Backup FTP password
 *
 * HTTP method: POST
 * Endpoint: /dedicated/housing/{serviceName}/features/backupFTP/password
 */
export async function execute(this: IExecuteFunctions,
	_itemIndex: number): Promise<INodeExecutionData[]> {
	const serviceName = this.getNodeParameter('serviceName', _itemIndex) as string;
	const client = getClient(this);
	const data = (await client.httpPost('/dedicated/housing/' + encodeURIComponent(serviceName) + '/features/backupFTP/password')) as IDataObject;
	return this.helpers.returnJsonArray([data]);
}
